void i18n.use(initReactI18next).init({
  resources: { "zh-TW": zhTW, en },
  lng: localStorage.getItem("langcraft-locale") ?? "zh-TW",
  fallbackLng: "zh-TW",
  interpolation: { escapeValue: false },
});

export async function setLocale(locale: "zh-TW" | "en") {
  localStorage.setItem("langcraft-locale", locale);
  await i18n.changeLanguage(locale);
}

